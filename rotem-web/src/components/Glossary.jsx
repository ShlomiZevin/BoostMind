export default function Glossary() {
  const [q, setQ] = useState('')
  const needle = q.trim().toLowerCase()
  const list = needle
    ? TERMS.filter((t) => t.join(' ').toLowerCase().includes(needle))
    : TERMS

  return (
    <div>
      <input
        className="search"
        placeholder="חיפוש מונח…  (למשל: token, נורמליזציה, deploy)"
        value={q}
        onChange={(e) => setQ(e.target.value)}
      />
      <div className="card" style={{ padding: '4px 20px' }}>
        {list.map(([en, he, def]) => (
          <div className="term" key={en}>
            <div className="term-head">
              <span className="term-en">{en}</span>
              {he !== '—' && <span className="term-he">{he}</span>}
            </div>
            <p>{def}</p>
          </div>
        ))}
        {list.length === 0 && <p style={{ padding: '16px 0' }}>לא נמצא מונח כזה. נסי מילה אחרת.</p>}
      </div>
    </div>
  )
}

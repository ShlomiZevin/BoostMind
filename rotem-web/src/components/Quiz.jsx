export default function Quiz() {
  const [answers, setAnswers] = useState({})

  const pick = (qi, oi) => {
    if (answers[qi] !== undefined) return
    setAnswers({ ...answers, [qi]: oi })
  }

  const answered = Object.keys(answers).length
  const correct = Object.entries(answers).filter(([qi, oi]) => QUESTIONS[qi].a === oi).length

  return (
    <div>
      {QUESTIONS.map((q, qi) => {
        const chosen = answers[qi]
        const done = chosen !== undefined
        return (
          <div className="quiz-q" key={qi}>
            <h4>
              {qi + 1}. {q.q}
            </h4>
            <div className="quiz-opts">
              {q.opts.map((o, oi) => {
                let cls = 'quiz-opt'
                let mark = ''
                if (done && oi === q.a) {
                  cls += ' right'
                  mark = '✓'
                } else if (done && oi === chosen) {
                  cls += ' wrong'
                  mark = '✕'
                }
                return (
                  <button key={oi} className={cls} onClick={() => pick(qi, oi)} disabled={done}>
                    <span>{o}</span>
                    {mark && <span className="mark">{mark}</span>}
                  </button>
                )
              })}
            </div>
            {done && <div className="quiz-explain">{q.why}</div>}
          </div>
        )
      })}

      {answered > 0 && (
        <div className="quiz-score">
          <div className="big">
            {correct} / {QUESTIONS.length}
          </div>
          <p style={{ margin: '4px 0 12px' }}>
            {answered < QUESTIONS.length
              ? `ענית על ${answered} מתוך ${QUESTIONS.length}`
              : correct === QUESTIONS.length
                ? 'מושלם. את מוכנה לפתוח את Claude Code ולהתחיל לבנות 🚀'
                : correct >= 7
                  ? 'ממש טוב. עברי שוב על הפרקים שטעית בהם ואת בפנים.'
                  : 'לא נורא — תחזרי על הפרקים ותנסי שוב. זה נכנס מהר.'}
          </p>
          <button className="btn" onClick={() => setAnswers({})}>
            ↺ להתחיל מחדש
          </button>
        </div>
      )}
    </div>
  )
}

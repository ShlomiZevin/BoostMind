/** the text of a label (a string, or a label with a "clip ×" mark beside it) */
export function labelText(l: any): string {
  if (l == null || typeof l === 'boolean') return '';
  if (typeof l === 'string' || typeof l === 'number') return String(l);
  if (Array.isArray(l)) return l.map(labelText).join('');
  if (l.props?.children !== undefined && !l.props?.S) return labelText(l.props.children);
  return '';
}
export const helpFor = (label: any) => HELP[labelText(label).trim()];

const res = await fetch('https://api.openai.com/v1/chat/completions', {
  method: 'POST',
  headers: headers(),
  body: JSON.stringify({
    model: MODEL,
    response_format: { type: 'json_object' },
    messages: [
      { role: 'system', content: SYSTEM },
      { role: 'user', content: BRIEF },
    ],
  }),
});


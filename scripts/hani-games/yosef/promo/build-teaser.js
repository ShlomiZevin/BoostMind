function probe(f) {
  try { execFileSync(FF, ['-i', f], { stdio: ['ignore', 'ignore', 'pipe'] }); } catch (e) { const m = /Duration: (\d+):(\d+):([\d.]+)/.exec(e.stderr.toString()); return +m[1] * 3600 + +m[2] * 60 + +m[3]; }
}
function prep(c, name) {
  const out = path.join(CL, name + '.wav'), ch = [];
  if (c.to != null) ch.push(`atrim=${c.from}:${c.to}`, 'asetpts=PTS-STARTPTS');
  if (!c.keep) {
    const trim = 'silenceremove=start_periods=1:start_threshold=-42dB:start_silence=0.03';
    ch.push(trim, 'areverse', trim, 'areverse', 'silenceremove=stop_periods=-1:stop_duration=0.12:stop_threshold=-42dB');
  }
  if (c.tempo) ch.push(`atempo=${c.tempo}`);
  ch.push('afade=t=in:d=0.02', 'aformat=sample_rates=44100:channel_layouts=stereo');
  execFileSync(FF, ['-y', '-i', path.join(Y, c.f), '-af', ch.join(','), out], { stdio: 'ignore' });
  return { f: path.relative(Y, out).replace(/\\/g, '/'), d: probe(out), abs: out };
}
async function words(file) {
  const f = new FormData(); f.append('model_id', 'scribe_v1'); f.append('language_code', 'he'); f.append('timestamps_granularity', 'word');
  f.append('file', new Blob([fs.readFileSync(file)]), 'a.wav');
  const r = await fetch('https://api.elevenlabs.io/v1/speech-to-text', { method: 'POST', headers: { 'xi-api-key': process.env.ELEVENLABS_API_KEY }, body: f });
  return ((await r.json()).words || []).filter((w) => w.type === 'word');
}
(async () => {
  const tl = { _: 'GENERATED by build-teaser.js - edit the BEATS there, not this file.', frames: [], clips: [], sfx: [], fine: null };
  let t = 0;
  for (const [bi, b] of BEATS.entries()) {
    const start = t, at = [];
    t += CUT;
    for (const [si, c] of b.say.entries()) {
      const p = prep(c, `${b.img}-${si}`);
      tl.clips.push({ f: p.f, at: +t.toFixed(3), raw: true, gain: c.gain || 1 });
      at.push(t);
      if (c.fine) {   // fine print synced to the words
        const w = await words(p.abs); let k = 0;
        tl.fine = { from: +start.toFixed(3), lines: FINE.map(([txt, n]) => { const s = w[Math.min(k, w.length - 1)].start; k += n; return { text: txt, at: +(t + s).toFixed(3) }; }) };
      }
      t += p.d + (si < b.say.length - 1 ? GAP : 0);
    }
    t += b.tail || TAIL;
    tl.frames.push({ img: b.img, from: +start.toFixed(3), to: +t.toFixed(3) });
    for (const [n, when, g] of b.sfx || []) {   // when: seconds from the beat start, or 'v1' / 'v1+x' = the beat's 2nd voice
      const s = typeof when === 'number' ? start + when : at[+when[1]] + (+(when.split('+')[1] || 0));
      tl.sfx.push([n, +s.toFixed(3), g]);
    }
  }
  tl.total = +t.toFixed(3); tl.fine.to = tl.frames.find((f) => f.img === 'f7').to;
  fs.writeFileSync(path.join(__dirname, 'teaser-tl.json'), JSON.stringify(tl, null, 1), 'utf8');
  console.log('total', tl.total, 's |', tl.frames.map((f) => `${f.img} ${(f.to - f.from).toFixed(1)}`).join(' | '));
})().catch((e) => { console.error('FAILED', e.message); process.exit(1); });

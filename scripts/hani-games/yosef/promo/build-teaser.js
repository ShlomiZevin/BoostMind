// builds teaser-tl.json from a short list of BEATS: each beat = one designed frame + the voices said over it, back to back.
// Every voice is pre-cut into out/clips/*.wav (silence trimmed at both ends, long pauses inside shortened, sped up), measured,
// and laid one after the other - so the pace is tight and nothing has to be timed by hand. The disclaimer is kept as is (only its
// speed) and its fine print is synced line by line to its words (ElevenLabs scribe timestamps).
//   . ~/.plaxzy/eleven-env.sh; node promo/build-teaser.js      then: node promo/render-teaser.js [--draft]

/**
 * invest-copy-review.mjs
 *
 * Runs the Hebrew copy of the Trip Planner investor page through OpenAI for
 * phrasing + review, following the briefing protocol in MARKETING.md §4:
 *   1. send the full brief   2. send the EXACT current text of every string
 *   3. ask for JSON, one field per string, plus a `why`
 *   4. state explicitly that "change nothing" is a valid answer
 *   5. then judge it  <-- human step. Nothing is written by this script.
 *
 * Usage:
 *   node scripts/invest-copy-review.mjs                 # default gpt-5.6-sol
 *   node scripts/invest-copy-review.mjs --model gpt-5.6-terra
 *   node scripts/invest-copy-review.mjs --out scripts/invest-review.out.json
 *   node scripts/invest-copy-review.mjs --apply scripts/invest-review.out.json   # judge the text as it shipped
 *
 * Key source: same as cv-phrase-review.mjs — MARKETING.md §4 names
 * aspect/aspect-agent-server/.env as the OpenAI source of truth. BoostMind's
 * own .env holds a revoked key. Override with --env-file <path>.
 */

import { writeFileSync, readFileSync, existsSync } from 'node:fs';

const argv = process.argv.slice(2);
const arg = (name, dflt) => {
  const i = argv.indexOf('--' + name);
  return i !== -1 && argv[i + 1] ? argv[i + 1] : dflt;
};
const MODEL = arg('model', 'gpt-5.6-sol');
const OUT = arg('out', 'scripts/invest-review.out.json');

const KEY_FILE = arg('env-file', 'C:/workspace/aspect/aspect-agent-server/.env');
const readEnvFile = (path) => {
  if (!path || !existsSync(path)) return {};
  const out = {};
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)$/);
    if (m) out[m[1]] = m[2].trim().replace(/^["']|["']$/g, '');
  }
  return out;
};
const fileEnv = readEnvFile(KEY_FILE);
const KEY = fileEnv.OPENAI_API_KEY || process.env.OPENAI_API_KEY;
const ORG = fileEnv.OPENAI_ORG_ID || process.env.OPENAI_ORG_ID;
const PROJ = fileEnv.OPENAI_PROJECT_ID || process.env.OPENAI_PROJECT_ID;

const die = (m) => { console.error('✖ ' + m); process.exit(1); };
if (!KEY) die('OPENAI_API_KEY missing. Checked ' + KEY_FILE);

const headers = () => {
  const h = { Authorization: 'Bearer ' + KEY, 'Content-Type': 'application/json' };
  if (ORG) h['OpenAI-Organization'] = ORG;
  if (PROJ) h['OpenAI-Project'] = PROJ;
  return h;
};

